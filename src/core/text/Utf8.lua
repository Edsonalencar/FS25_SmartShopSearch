--- Dobra acentos: substitui sequências de 2 bytes presentes em `Utf8.FOLD`
--- pelo equivalente ASCII. Sequências de 3/4 bytes (outros alfabetos) são
--- apenas puladas/preservadas como bytes, nunca quebradas.
---@param s string
---@return string
function Utf8.fold(s)
    if not s:find("[\128-\255]") then
        return s -- atalho: ASCII puro, nada para dobrar
    end
    local out = {}
    local i, n = 1, #s
    while i <= n do
        local b = string.byte(s, i)
        if b < 0xC0 then
            out[#out + 1] = string.char(b)
            i = i + 1
        else
            local seqLen = 2
            if b >= 0xF0 then
                seqLen = 4
            elseif b >= 0xE0 then
                seqLen = 3
            end
            local seq = string.sub(s, i, i + seqLen - 1)
            if seqLen == 2 and Utf8.FOLD[seq] then
                out[#out + 1] = Utf8.FOLD[seq]
            else
                out[#out + 1] = seq
            end
            i = i + seqLen
        end
    end
    return table.concat(out)
end

--- Conta bytes que não sejam de continuação (b < 0x80 ou b >= 0xC0) — ou
--- seja, o número de "caracteres" (aproximado) em uma string UTF-8.
---@param s string
---@return integer
function Utf8.len(s)
    local n = 0
    for i = 1, #s do
        local b = string.byte(s, i)
        if b < 0x80 or b >= 0xC0 then
            n = n + 1
        end
    end
    return n
end

